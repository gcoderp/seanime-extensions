def test_validator_rejects_broken_javascript():
    ts, js = _sample_extension()
    # Any unparseable token must be caught by the node --check gate
    broken = js + "\nconst = 1;\n"
    result = _validator().validate_extension(
        "x", "onlinestream-provider", ts, broken,
        main_url="https://anitaku.pe", license_spdx="TEST_FIXTURE", strategy="STRATEGY_1_EMBEDDED_KOTLIN_SOURCE",
    )
    assert result["overall_status"] == "FAILED"
    assert any("does not parse" in e for e in result["errors"])


